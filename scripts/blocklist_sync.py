#!/usr/bin/env python3
"""blocklist_sync - keep the organisation-wide datapack blocklist in step with
vortaforge/core, and profile-scan accounts that touch the organisation.

Two independent jobs, both offline by default:

1. Mirror (`--check` / `--write`)
   Reads `vortaforge/core`'s `blocklist/blocklist.json` (a local checkout via
   `--core`, or the raw GitHub URL with `--fetch`) and writes
   `blocklist/blocklist.json` + `generated/blocklist.json` in this repository.
   `--check` exits 1 when the two differ, so the workflow can fail instead of
   silently drifting.

2. Profile scan (`--scan-profiles`) - REMOVED 2026-11-08, see below
   For each login given on the command line (or in `--logins-file`), reads the
   **public** GitHub profile (`bio`, `company`, `name`, `blog`) with `gh api`
   ~~and reports whether it matches a `policy.profile_tokens` entry~~. The
   token list and the scan itself were removed on 2026-11-08 together with the
   two named-author entries they existed to find: scanning public bios to infer
   that someone belongs to a category of person is the part of the old design
   least worth keeping, and a flag whose token list is empty scans nothing. The
   command stays so that an old caller fails with a clear message rather than a
   KeyError. It never blocks anyone by itself: it writes `generated/profile-scan.json` and exits 1 when
   there are unresolved hits (fail-closed: the caller opens an issue).

Only the Python standard library plus whatever `gh` is authenticated as. No
token is ever printed or written. Public profile fields only - no private data,
no global GitHub search, no scraping.

Usage
-----
    python3 scripts/blocklist_sync.py --check --core ../core
    python3 scripts/blocklist_sync.py --write --core ../core
    python3 scripts/blocklist_sync.py --scan-profiles --login someone
    python3 scripts/blocklist_sync.py --scan-profiles --logins-file /tmp/logins.txt

Exit: 0 ok / no hits, 1 drift or unresolved hits, 2 usage or environment error.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "blocklist" / "blocklist.json"
GENERATED = ROOT / "generated" / "blocklist.json"
SCAN_REPORT = ROOT / "generated" / "profile-scan.json"
RAW_URL = "https://raw.githubusercontent.com/vortaforge/core/main/blocklist/blocklist.json"
PROFILE_FIELDS = ("login", "name", "company", "bio", "blog", "twitter_username")


def load_source(core: Path | None, fetch: bool) -> dict:
    if core is not None:
        path = (core / "blocklist" / "blocklist.json").resolve()
        if not path.is_file():
            raise SystemExit(f"blocklist_sync: {path} does not exist")
        return json.loads(path.read_text(encoding="utf-8"))
    if fetch:
        with urllib.request.urlopen(RAW_URL, timeout=30) as response:  # noqa: S310 - fixed URL
            return json.loads(response.read().decode("utf-8"))
    raise SystemExit("blocklist_sync: pass --core <path-to-core-checkout> or --fetch")


def normalise(data: dict) -> dict:
    """Make the mirrored copy deterministic and mark it as generated.

    `generated_on` deliberately mirrors the *source's own* `updated_on` rather
    than today's date. Using today's date made the mirror depend on when it was
    generated: a pristine mirror checked the next day would differ from a fresh
    render, so `--check` reported drift against an unchanged source and the
    daily workflow committed a no-op every single day. The mirror must be a
    pure function of the source.
    """
    out = json.loads(json.dumps(data))  # deep copy
    out["generated_from"] = "https://github.com/vortaforge/core/blob/main/blocklist/blocklist.json"
    source_date = out.get("updated_on")
    out["generated_on"] = source_date if isinstance(source_date, str) and source_date else None
    out["$comment"] = (
        "DO NOT EDIT BY HAND. Generated by scripts/blocklist_sync.py from "
        "vortaforge/core's blocklist/blocklist.json. Edit the source there; "
        "the datapack-blocklist-sync workflow regenerates this file."
    )
    out.setdefault("managed", {})
    out.setdefault("policy", {})
    out["blocked"] = sorted(out.get("blocked", []), key=lambda entry: str(entry.get("id", "")))
    return out


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def _problems(source: dict, rendered: str) -> list[str]:
    """Everything that does not match a fresh render of `source`.

    Both published copies are compared. `generated/blocklist.json` used to be
    written but never verified, so a corrupt or stale copy passed `--check`
    while being the file other tooling reads.
    """
    problems = []
    for label, path in (("blocklist/blocklist.json", TARGET),
                        ("generated/blocklist.json", GENERATED)):
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current != rendered:
            problems.append(label)
    return problems


def mirror(core: Path | None, fetch: bool, write: bool) -> int:
    source = normalise(load_source(core, fetch))
    rendered = json.dumps(source, indent=2, ensure_ascii=False) + "\n"
    problems = _problems(source, rendered)
    if not problems:
        print("[blocklist_sync] mirror is up to date")
        return 0
    if not write:
        print("[blocklist_sync] DRIFT: " + " and ".join(problems)
              + " differ from vortaforge/core")
        return 1
    # Write both, then re-verify: a partial write is the failure mode that made
    # the unchecked copy possible in the first place.
    write_json(TARGET, source)
    write_json(GENERATED, source)
    remaining = _problems(source, rendered)
    if remaining:
        print("[blocklist_sync] ERROR: still inconsistent after write: "
              + ", ".join(remaining), file=sys.stderr)
        return 2
    print("[blocklist_sync] mirror updated")
    return 0


def gh_profile(login: str) -> dict | None:
    """Public profile fields for one login, via an authenticated `gh`."""
    fields = ",".join(PROFILE_FIELDS)
    proc = subprocess.run(
        ["gh", "api", f"users/{login}", "--jq",
         "{" + ",".join(f"{f}: .{f}" for f in PROFILE_FIELDS) + "}"],
        capture_output=True, text=True, check=False, timeout=60,
    )
    if proc.returncode != 0:
        print(f"[blocklist_sync] warn: gh api failed for {login}: {proc.stderr.strip()[:200]}")
        return None
    try:
        return json.loads(proc.stdout)
    except json.JSONDecodeError:
        return None


def scan(profile: dict, policy: dict) -> dict:
    # No tokens, no scan. `policy.profile_tokens` was removed from the blocklist
    # on 2026-11-08; a missing key is now the normal state rather than a
    # misconfiguration, so this returns "clean" instead of failing.
    tokens = [t.lower() for t in policy.get("profile_tokens", [])]
    exempt = [t.lower() for t in policy.get("profile_exempt_tokens", [])]
    if not tokens:
        return {"login": profile.get("login"), "matched_tokens": [], "exemptions": [],
                "verdict": "clean"}
    # `blog` is documented in blocklist/README.md as a scanned field and is
    # fetched by PROFILE_FIELDS, but was missing here, so a profile carrying the
    # matching token only in its website link was reported clean.
    haystack = " ".join(
        str(profile.get(field) or "") for field in ("bio", "company", "name", "blog")
    ).lower()
    hits = [token for token in tokens if token in haystack]
    exemptions = [token for token in exempt if token in haystack]
    return {
        "login": profile.get("login"),
        "matched_tokens": hits,
        "exemptions": exemptions,
        "verdict": "exempt" if exemptions else ("hit" if hits else "clean"),
    }


def scan_profiles(logins: list[str]) -> int:
    policy = json.loads(TARGET.read_text(encoding="utf-8")).get("policy", {})
    if not policy.get("profile_scan") or not policy.get("profile_tokens"):
        # `profile_scan` and its token lists were removed from the blocklist on
        # 2026-11-08 with the named-author entries they were built to find. Both
        # keys are absent now, so this is the normal path: nothing to scan, exit
        # clean. The distinction that matters is between "not configured" and
        # "configured and found nothing", and only the second is evidence.
        print("[blocklist_sync] profile scan is not configured; nothing to scan")
        return 0
    managed = {
        str(x).lower()
        for x in (json.loads(TARGET.read_text(encoding="utf-8")).get("managed", {})
                  .get("owners", []) + json.loads(TARGET.read_text(encoding="utf-8"))
                  .get("managed", {}).get("accounts", []))
    }
    results = []
    hits = 0
    for login in logins:
        login = login.strip()
        if not login or login.lower() in managed:
            continue
        profile = gh_profile(login)
        if profile is None:
            results.append({"login": login, "verdict": "unknown", "matched_tokens": [],
                            "exemptions": []})
            hits += 1  # fail-closed: an unreadable profile is not a pass
            continue
        result = scan(profile, policy)
        results.append(result)
        if result["verdict"] == "hit":
            hits += 1
    write_json(SCAN_REPORT, {"generated_on": date.today().isoformat(),
                             "policy_action": policy.get("profile_scan_action", "block"),
                             "results": results})
    for result in results:
        print(f"[blocklist_sync] {result['login']}: {result['verdict']} "
              f"{result['matched_tokens'] or ''}")
    print(f"[blocklist_sync] profile scan: {len(results)} account(s), {hits} unresolved hit(s)")
    return 1 if hits else 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--core", type=Path, default=os.environ.get("CORE_CHECKOUT"),
                        help="path to a vortaforge/core checkout")
    parser.add_argument("--fetch", action="store_true", help="read the raw file from GitHub")
    parser.add_argument("--check", action="store_true", help="fail on drift, write nothing")
    parser.add_argument("--write", action="store_true", help="update the mirror")
    parser.add_argument("--scan-profiles", action="store_true", help="scan public profiles")
    parser.add_argument("--login", action="append", default=[], help="account to scan")
    parser.add_argument("--logins-file", type=Path, help="newline-separated accounts to scan")
    args = parser.parse_args(argv)

    if args.scan_profiles:
        logins = list(args.login)
        if args.logins_file and args.logins_file.is_file():
            logins += [line.strip() for line in
                       args.logins_file.read_text(encoding="utf-8").splitlines() if line.strip()]
        return scan_profiles(logins)
    if not (args.check or args.write):
        print("blocklist_sync: pass --check or --write (or --scan-profiles)", file=sys.stderr)
        return 2
    return mirror(args.core, args.fetch, args.write)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
